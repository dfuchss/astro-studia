/**
 * Rewrite verification/asset-sha256.txt from what is in public/ (`npm run
 * baseline`). A deliberate act, never part of the build: the baseline exists
 * so a published file cannot change without someone meaning it to. Commit the
 * result together with the asset.
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = process.cwd();
const PUBLIC = join(ROOT, 'public');
const OUT = join(ROOT, 'verification/asset-sha256.txt');

/**
 * What the baseline covers. Narrow on purpose: a PDF you have published is
 * cited and indexed and must never be re-encoded, whereas the favicons are
 * generated from the SVG and are expected to change when it does.
 */
const COVERED = /^assets\//;

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

const rows = walk(PUBLIC)
  .map((f) => relative(PUBLIC, f).split('\\').join('/'))
  .filter((rel) => COVERED.test(rel))
  .sort()
  .map(
    (rel) =>
      `${createHash('sha256')
        .update(readFileSync(join(PUBLIC, rel)))
        .digest('hex')}  ${rel}`,
  );

mkdirSync(join(ROOT, 'verification'), { recursive: true });
writeFileSync(
  OUT,
  `# SHA-256 of every file under public/assets/, as published.
#
# Generated by scripts/generate-asset-baseline.mjs; checked by
# scripts/verify-invariants.mjs, which the deploy workflow runs before it
# publishes anything.
#
# Why this exists: a PDF you have published is cited in other people's papers
# and indexed by Google Scholar, DBLP and your institutional repository. Those
# URLs are permanent whether or not you meant them to be, and the way they
# break is never a deliberate deletion — it is an image optimiser, a helpful
# "clean up assets" commit, or a tool that rewrites a file in place. None of
# those announce themselves.
#
# To add or replace an asset on purpose: npm run baseline, and commit both.
${rows.length ? '\n' + rows.join('\n') + '\n' : '\n'}`,
);

console.log(`wrote ${relative(ROOT, OUT)} — ${rows.length} file(s)`);
